// Longest prefix wins: 'EA8…' must match EA8 (Canaries), not EA (Spain).
const SORTED = [...TABLE].sort((a, b) => b[0].length - a[0].length);

export function callToLatLon(call: string): LatLon | null {
  const c = call.trim().toUpperCase();
  const hit = SORTED.find(([p]) => c.startsWith(p));
  return hit ? { lat: hit[1], lon: hit[2] } : null;
}

/**
 * Deterministic per-call jitter (±1.2°) so spots from the same entity spread
 * into a visible cluster instead of stacking on one pixel.
 */
export function callJitter(call: string): { dLat: number; dLon: number } {
  let h = 0;
  for (let i = 0; i < call.length; i++) h = (h * 31 + call.charCodeAt(i)) | 0;
  const a = ((h & 0xffff) / 0xffff - 0.5) * 2.4;
  const b = (((h >>> 16) & 0xffff) / 0xffff - 0.5) * 2.4;
  return { dLat: a, dLon: b };
}
